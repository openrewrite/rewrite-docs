#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

const ROOT = path.resolve(__dirname, '..');
const DOCS_DIR = path.join(ROOT, 'docs');

// Generated per-module pages, linked from reference/all-recipes.
const ALLOWED_OUTSIDE_SIDEBAR = /^reference\/all-recipes-/;

// The homepage, linked from the logo.
const ALLOWED_OUTSIDE_NAV = new Set(['introduction']);

// Node 20 cannot import TypeScript, and these modules use the @site alias that
// only webpack resolves, so they are transpiled and wired up by hand.
const loaded = new Map();
function loadTs(file) {
  if (loaded.has(file)) {
    return loaded.get(file).exports;
  }
  const { outputText } = ts.transpileModule(fs.readFileSync(file, 'utf-8'), {
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2022,
      esModuleInterop: true,
    },
  });
  const mod = { exports: {} };
  loaded.set(file, mod);
  const localRequire = (id) =>
    id.startsWith('@site/') ? loadTs(path.join(ROOT, `${id.slice('@site/'.length)}.ts`)) : require(id);
  new Function('require', 'module', 'exports', outputText)(localRequire, mod, mod.exports);
  return mod.exports;
}

const sidebar = loadTs(path.join(ROOT, 'sidebars.ts')).default.docs;
const { primarySections, releaseSections, mobileSections, ownerOf } = loadTs(
  path.join(ROOT, 'src/config/navSections.ts'),
);

function listDocs(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      return listDocs(full);
    }
    // Docusaurus skips underscore-prefixed partials (`exclude` in docusaurus.config.ts).
    return /\.mdx?$/.test(entry.name) && !entry.name.startsWith('_') ? [full] : [];
  });
}

const docFiles = new Map(
  listDocs(DOCS_DIR).map((file) => [
    path.relative(DOCS_DIR, file).split(path.sep).join('/').replace(/\.mdx?$/, ''),
    file,
  ]),
);

function collectSidebar(items, docIds, autogeneratedDirs) {
  for (const item of items) {
    if (typeof item === 'string') {
      docIds.add(item);
      continue;
    }
    if (item.type === 'doc') {
      docIds.add(item.id);
    }
    if (item.type === 'autogenerated') {
      autogeneratedDirs.push(`${item.dirName}/`);
    }
    if (item.link?.type === 'doc') {
      docIds.add(item.link.id);
    }
    if (Array.isArray(item.items)) {
      collectSidebar(item.items, docIds, autogeneratedDirs);
    }
  }
}

const sidebarDocIds = new Set();
const autogeneratedDirs = [];
collectSidebar(sidebar, sidebarDocIds, autogeneratedDirs);

const isRedirectStub = (file) => /<Redirect\b/.test(fs.readFileSync(file, 'utf-8'));
const normalize = (href) => href.toLowerCase().replace(/\/$/, '');

const problems = [];

for (const [id, file] of docFiles) {
  if (sidebarDocIds.has(id) || autogeneratedDirs.some((dir) => id.startsWith(dir))) {
    continue;
  }
  if (isRedirectStub(file) || ALLOWED_OUTSIDE_SIDEBAR.test(id)) {
    continue;
  }
  problems.push(`docs/${path.relative(DOCS_DIR, file)} is not in sidebars.ts.`);
}

for (const id of sidebarDocIds) {
  if (!docFiles.has(id)) {
    problems.push(`sidebars.ts references '${id}', which has no file under docs/.`);
  }
}

const navHrefs = new Set([...primarySections, ...releaseSections, ...mobileSections].map((s) => normalize(s.href)));
for (const id of sidebarDocIds) {
  if (!ALLOWED_OUTSIDE_NAV.has(id) && !navHrefs.has(ownerOf(`/${id}`))) {
    problems.push(
      `'${id}' is not in a sidebar category linked from the menus. ` +
        'Move it into one, or add a section for it in src/config/navSections.ts.',
    );
  }
}

const categorySlugs = new Set(sidebar.filter((item) => item.link?.slug).map((item) => normalize(item.link.slug)));
for (const section of new Set([...primarySections, ...mobileSections])) {
  if (!categorySlugs.has(normalize(section.href))) {
    problems.push(
      `Nav section '${section.name}' links to ${section.href}, which matches no top-level category slug in sidebars.ts.`,
    );
  }
}

if (problems.length > 0) {
  console.error('Menu coverage problems:\n');
  for (const problem of problems) {
    console.error(`  ${problem}`);
  }
  console.error(
    '\nIf a page is meant to sit outside the menus, add it to an allowlist in scripts/check-orphaned-pages.js.',
  );
  process.exit(1);
}

console.log(`All ${docFiles.size} docs are reachable from the menus.`);
